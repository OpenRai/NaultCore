import { test, expect, unlockWalletThroughBridge } from './fixtures';
import CryptoJS from 'crypto-js';
import { deriveAddress, derivePublicKey, deriveSecretKey } from 'nanocurrency';
import { e2eWalletPassword } from './test-wallet';
test.use({ storageState: { cookies: [], origins: [] } });

for (const width of [1280, 393]) {
  test(`explicit derivation selection and return focus at ${width}px`, async ({ page: seededPage }) => {
    const seed = '0'.repeat(64);
    const accounts = [0, 1, 2].map(index => ({ index, id: deriveAddress(derivePublicKey(deriveSecretKey(seed, index)), { useNanoPrefix: true }) }));
    const wallet = JSON.stringify({ type: 'seed', seed: CryptoJS.AES.encrypt(seed, e2eWalletPassword).toString(), locked: true, accounts, selectedAccountId: null });
    await seededPage.addInitScript(({ wallet, namedAccount }) => {
      localStorage.setItem('nanovault-wallet', wallet);
      localStorage.setItem('nanovault-addressbook', JSON.stringify([{ account: namedAccount, name: 'Savings', trackBalance: false, trackTransactions: false }]));
    }, { wallet, namedAccount: accounts[1].id });
    await seededPage.goto('/accounts/derive');
    const unlockHint = seededPage.getByRole('status').filter({ hasText: 'to enable deriving account keys and addresses.' });
    await expect(unlockHint).toHaveText('Unlock your wallet to enable deriving account keys and addresses.');
    await expect(unlockHint.getByRole('button', { name: 'Unlock your wallet', exact: true })).toBeVisible();
    await expect(seededPage.getByText('Unable to derive accounts.', { exact: false })).toHaveCount(0);
    await unlockWalletThroughBridge(seededPage);
    await expect(seededPage.getByRole('checkbox')).toHaveCount(5);
    await expect(unlockHint).toHaveCount(0);
    await seededPage.getByRole('navigation', { name: 'Breadcrumb', exact: true }).getByRole('link', { name: 'Accounts', exact: true }).click();
    await seededPage.setViewportSize({ width, height: 852 });
    const before = await seededPage.evaluate(() => localStorage.getItem('nanovault-wallet'));
    await seededPage.getByRole('button', { name: 'Add accounts…' }).click();
    await expect(seededPage.getByRole('heading', { name: 'Derive accounts' })).toHaveCount(0);
    await expect(seededPage.getByText('Derive accounts from wallet seed', { exact: true })).toBeVisible();
    const breadcrumb = seededPage.getByRole('navigation', { name: 'Breadcrumb', exact: true });
    await expect(breadcrumb.getByRole('link', { name: 'Accounts', exact: true })).toHaveAttribute('href', '/accounts');
    await expect(breadcrumb.locator('[aria-current="page"]')).toHaveText('Add');
    const tracked = seededPage.locator('[data-account-index="0"]');
    await expect(tracked).toHaveClass(/uk-text-muted/);
    await expect(tracked.getByRole('checkbox', { name: 'Account #0', exact: true })).toBeChecked();
    await expect(tracked.getByRole('checkbox')).toBeDisabled();
    await expect(seededPage.locator('[data-account-index="1"]').getByRole('checkbox', { name: 'Savings', exact: true })).toBeChecked();
    await expect(tracked.getByText('Already added', { exact: true })).toHaveCount(0);
    const checkBounds = await tracked.getByRole('checkbox').boundingBox();
    const textBounds = await tracked.locator('.derive-account-details').boundingBox();
    expect(checkBounds!.x).toBeGreaterThan(textBounds!.x + textBounds!.width);
    expect(await seededPage.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
    await expect(seededPage.getByRole('checkbox')).toHaveCount(5);
    await expect(seededPage.getByText('Remaining capacity: 17', { exact: true })).toBeVisible();
    await expect(seededPage.getByRole('button', { name: 'Add selected accounts (0)' })).toBeDisabled();
    await seededPage.getByRole('button', { name: 'Next', exact: true }).click();
    await expect(seededPage.getByRole('checkbox')).toHaveCount(5);
    expect(await seededPage.evaluate(() => localStorage.getItem('nanovault-wallet'))).toBe(before);
    await seededPage.getByRole('checkbox').first().check();
    await expect(seededPage.getByText('Remaining capacity: 16', { exact: true })).toBeVisible();
    await seededPage.getByRole('button', { name: 'Next', exact: true }).click();
    await expect(seededPage.getByRole('checkbox')).toHaveCount(5);
    await seededPage.getByRole('checkbox').first().check();
    await seededPage.getByRole('button', { name: 'Previous', exact: true }).click();
    await expect(seededPage.getByRole('checkbox').first()).toBeChecked();
    await seededPage.getByRole('button', { name: 'Add selected accounts (2)' }).click();
    await expect(seededPage).toHaveURL(/\/accounts$/);
    await expect(seededPage.locator('.account-added')).toHaveCount(2);
    await expect(seededPage.locator('.account-added').first()).toBeFocused();
    await expect(seededPage.getByRole('status')).toContainText('Added 2 accounts');
    await seededPage.locator('.account-added').first().getByTestId('accounts-row-details-button').click();
    await expect(seededPage.getByRole('navigation', { name: 'Breadcrumb', exact: true })).toBeVisible();
    await expect(seededPage.locator('h2.uk-heading-divider')).toHaveCount(0);
    await seededPage.getByRole('navigation', { name: 'Breadcrumb', exact: true }).getByRole('link', { name: 'Accounts', exact: true }).click();
    const edit = seededPage.getByRole('button', { name: 'Edit accounts', exact: true });
    await edit.focus();
    await seededPage.keyboard.press('Space');
    const done = seededPage.getByRole('button', { name: 'Done', exact: true });
    await expect(done).toHaveAttribute('aria-pressed', 'true');
    const hiddenRow = seededPage.locator(`[data-testid="accounts-row"][data-account-id="${accounts[0].id}"]`);
    await hiddenRow.getByRole('button', { name: /hide account/i }).filter({ visible: true }).click();
    await expect(hiddenRow).toHaveCount(0);
    await expect(seededPage.locator('.wallet-notification').filter({ hasText: `Account hidden: ${accounts[0].id}` })).toBeVisible();
    await done.click();
    await expect(edit).toHaveAttribute('aria-pressed', 'false');
  });
}
